// JavaScript has different data types such as strings, numbers and booleans.

const userName = 'Lili';
const age = 30;
const isLearning = true;

console.log(typeof userName);
console.log(typeof age);
console.log(typeof isLearning);

// When a number is added to a string, JavaScript performs string concatenation.
const years = '5';
console.log(age + years);

// Number() converts a string into a number.
const userAge = '30';
const convertedAge = Number(userAge);

console.log(typeof userAge);
console.log(typeof convertedAge);
console.log(convertedAge + 5);